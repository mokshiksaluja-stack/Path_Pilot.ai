from enum import Enum
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field


class TaskDifficulty(str, Enum):
    EASY = "EASY"
    MEDIUM = "MEDIUM"
    HARD = "HARD"


class TaskSchema(BaseModel):
    """
    Atomic 15-30 minute micro-task representation.
    Aligns directly with Prisma `DailyTask` relational table.
    """
    model_config = ConfigDict(populate_by_name=True)

    day_number: int = Field(
        ...,
        ge=1,
        alias="dayNumber",
        description="Day number of the curriculum (1 to N)"
    )
    title: str = Field(
        ...,
        min_length=3,
        max_length=150,
        description="Actionable task title focusing on a single concrete concept"
    )
    description: str = Field(
        ...,
        min_length=10,
        description="Clear, hands-on instructions for the learner"
    )
    estimated_mins: int = Field(
        default=30,
        ge=15,
        le=180,
        alias="estimatedMins",
        description="Estimated duration in minutes (typically 15-45 mins)"
    )
    difficulty: TaskDifficulty = Field(
        default=TaskDifficulty.MEDIUM,
        description="Perceived difficulty tier: EASY, MEDIUM, or HARD"
    )
    resource_url: Optional[str] = Field(
        default=None,
        alias="resourceUrl",
        description="Curated documentation, tutorial, or GitHub reference link"
    )


class MilestoneSchema(BaseModel):
    """
    Weekly or thematic phase milestone.
    Aligns directly with Prisma `Milestone` relational table.
    """
    model_config = ConfigDict(populate_by_name=True)

    title: str = Field(
        ...,
        min_length=5,
        max_length=200,
        description="Theme or week title, e.g. 'Week 1: Core Fundamentals & Syntax'"
    )
    order_index: int = Field(
        ...,
        ge=1,
        alias="orderIndex",
        description="Sequential order index of this milestone phase"
    )
    tasks: list[TaskSchema] = Field(
        default_factory=list,
        description="Ordered list of atomic daily micro-tasks belonging to this milestone"
    )


class RoadmapSchema(BaseModel):
    """
    Structured roadmap curriculum generated by the AI agent pipeline.
    Aligns directly with Prisma `Roadmap` entity.
    """
    model_config = ConfigDict(populate_by_name=True)

    summary: str = Field(
        ...,
        description="High-level pedagogical overview and learning outcome summary"
    )
    total_days: int = Field(
        ...,
        ge=1,
        alias="totalDays",
        description="Total duration in days"
    )
    milestones: list[MilestoneSchema] = Field(
        default_factory=list,
        description="Sequential list of weekly milestone phases"
    )


class GeneratedRoadmapEnvelope(BaseModel):
    """
    Top-level API response envelope matching API Gateway and Core Service contracts.
    """
    model_config = ConfigDict(populate_by_name=True)

    goal_id: Optional[str] = Field(
        default=None,
        alias="goalId",
        description="PostgreSQL Goal UUID if associated with an existing goal"
    )
    status: str = Field(
        default="SUCCESS",
        description="Execution status flag: SUCCESS or FAILED"
    )
    cached: bool = Field(
        default=False,
        description="Flag indicating whether roadmap was served from Redis cache (<15ms)"
    )
    roadmap: RoadmapSchema = Field(
        ...,
        description="Complete structured roadmap payload"
    )
